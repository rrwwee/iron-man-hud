import assert from 'node:assert/strict';
import {publishSnapshot} from '../../../tools/publish-codex-activity.mjs';
const old={schemaVersion:1,fetchedAt:'2026-10-15T12:00:00Z',lifetimeTokens:10,currentStreakDays:2,days:[{date:'2026-10-15',tokens:10}]};
const fresh={...old,fetchedAt:'2026-10-16T12:00:00Z',lifetimeTokens:20,privateToken:'secret',days:[{date:'2026-10-16',tokens:20,project:'private'}]};
const calls=[];
const api=async(method,body)=>{calls.push({method,body});return method==='GET'?{sha:'expected-file-sha',content:Buffer.from(JSON.stringify(old)).toString('base64')}:{commit:{sha:'new-commit'}};};
assert.equal((await publishSnapshot(fresh,api)).status,'published');
assert.equal(calls[1].body.branch,'main');assert.equal(calls[1].body.sha,'expected-file-sha');
const posted=JSON.parse(Buffer.from(calls[1].body.content,'base64').toString());
assert.equal('privateToken' in posted,false);assert.equal('project' in posted.days[0],false);
assert.deepEqual(Object.keys(posted).sort(),['currentStreakDays','days','fetchedAt','lifetimeTokens','schemaVersion'].sort());
calls.length=0;
assert.equal((await publishSnapshot(old,api)).status,'unchanged');assert.equal(calls.length,1);
calls.length=0;
assert.equal((await publishSnapshot({...old,fetchedAt:'2026-10-14T12:00:00Z',days:[{date:'2026-10-14',tokens:10}]},api)).status,'skipped');assert.equal(calls.length,1);
await assert.rejects(publishSnapshot({...fresh,lifetimeTokens:null},api),/Incomplete/);
await assert.rejects(publishSnapshot({...fresh,days:[]},api),/Incomplete/);
await assert.rejects(publishSnapshot(fresh,async()=>{throw new Error('offline');}),/offline/);
console.log('Codex publisher: public fields only, exact-file update, unchanged/stale skips and failure preservation pass.');
