import assert from 'node:assert/strict';
import {cleanProfile,loadPublicProfile} from '../public-profile.js';
import {flightSummary} from '../flight-routes.js';
const raw={login:'rrwwee',name:'Rory',bio:'Public bio',followers:4,public_repos:6,private_field:'never expose'};
assert.deepEqual(cleanProfile(raw),{login:'rrwwee',name:'Rory',bio:'Public bio',followers:4,public_repos:6});
assert.equal(cleanProfile({...raw,login:'someoneelse'}),null);
assert.equal(cleanProfile({...raw,followers:-1}),null);
assert.equal(cleanProfile({...raw,followers:1.5}),null);
let stored=null,calls=0;const storage={getItem:()=>stored,setItem:(_k,v)=>stored=v};
const fetcher=async()=>{calls++;return {ok:true,json:async()=>raw}};
assert.equal((await loadPublicProfile({fetcher,storage,now:100})).status,'live');
assert.equal((await loadPublicProfile({fetcher,storage,now:200})).followers,4);assert.equal(calls,1);
assert.equal((await loadPublicProfile({fetcher:async()=>{throw Error('offline')},storage,now:4000000})).status,'saved');
assert.equal(await loadPublicProfile({fetcher:async()=>({ok:false}),storage:{getItem:()=>null},now:100}),null);
const s=flightSummary([{from:[0,0],to:[90,0],count:2},{from:[90,0],to:[0,0],count:1}]);
assert.equal(s.flights,3);assert.equal(s.airports,2);assert.equal(s.routes,2);
assert.ok(Math.abs(s.miles-18655)<3,'Each flown leg counts its great-circle distance');
assert.equal(flightSummary([]).miles,0);
assert.equal(flightSummary([{from:[0,0],to:[180,0],count:1}]).miles,12437);
console.log('Public profile sanitization, cache/offline fallbacks and repeated-flight distance pass.');
