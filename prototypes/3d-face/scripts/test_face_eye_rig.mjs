import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {Group, Mesh, BufferGeometry, MeshBasicMaterial, Vector3} from '../vendor/three.module.js';
import {createFaceEyeRig} from '../face-eye-rig.js';
const raw = await fs.readFile(new URL('../assets/rory-head.glb', import.meta.url));
const gltf = JSON.parse(raw.subarray(20, 20 + raw.readUInt32LE(12)));
const root = new Group();
for (const node of gltf.nodes.filter(node => node.mesh !== undefined)) {
  const source = gltf.meshes[node.mesh];
  const mesh = new Mesh(new BufferGeometry(), new MeshBasicMaterial());
  mesh.name = node.name;
  mesh.morphTargetDictionary = Object.fromEntries(source.extras.targetNames.map((name, index) => [name, index]));
  mesh.morphTargetInfluences = source.extras.targetNames.map(() => 0);
  root.add(mesh);
}
const rig = createFaceEyeRig(root);
const left = rig.getPupilPosition('left', new Vector3()).clone();
const right = rig.getPupilPosition('right', new Vector3()).clone();
const weight = (mesh, key) => mesh.morphTargetInfluences[mesh.morphTargetDictionary[key]];
rig.apply({blinkLeft: 1});
assert.equal(weight(rig.meshes.face, 'blink_left_closed'), 1);
assert.equal(weight(rig.meshes.face, 'blink_right_closed'), 0);
assert.equal(weight(rig.meshes.face, 'blink_left_half'), 0);
rig.apply({blinkLeft: .5, blinkRight: .5});
assert.equal(weight(rig.meshes.face, 'blink_left_half'), 1);
assert.equal(weight(rig.meshes.face, 'blink_right_half'), 1);
rig.apply({yaw: .2, pitch: .14});
assert.ok(rig.getPupilPosition('right', new Vector3()).x > right.x);
assert.ok(rig.getPupilPosition('left', new Vector3()).x > left.x);
assert.ok(rig.getPupilPosition('right', new Vector3()).y < right.y);
assert.ok(Math.hypot(rig.state.yaw/(Math.PI/18), rig.state.pitch/(7*Math.PI/180)) <= 1 + 1e-12);
root.scale.setScalar(.16);root.rotation.y=.3;root.position.set(0,1.6,.07);
assert.ok(rig.getPupilWorldPosition('right', new Vector3()).toArray().every(Number.isFinite));
rig.apply();
assert.deepEqual(rig.getPupilPosition('left', new Vector3()), left);
assert.deepEqual(rig.getPupilPosition('right', new Vector3()), right);
for (const mesh of Object.values(rig.meshes)) assert.ok(mesh.morphTargetInfluences.every(value => value === 0));
rig.apply({yaw:NaN,pitch:Infinity,blinkLeft:-4,blinkRight:12});
assert.equal(rig.state.yaw,0);assert.equal(rig.state.pitch,0);assert.equal(rig.state.blinkLeft,0);assert.equal(rig.state.blinkRight,1);
console.log('Actual asset target names, isolated eyelids, conjugate bounded gaze, moving pupil anchors and exact neutral reset pass.');
